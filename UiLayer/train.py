    def strip_one_leading_trailing_blank(self,frame: str) -> str:
        # Your frames start/end with a blank line because of the triple quotes.
        # This makes counting + overwriting consistent.
        return frame.strip("\n")

    def render_frame(self, frame: str, prev_lines: int | None):
        frame = self.strip_one_leading_trailing_blank(frame)
        lines = frame.splitlines()

        if prev_lines is not None:
            # Move up to the start of the previous frame
            sys.stdout.write(f"\x1b[{prev_lines}A")
        # Clear and print new frame line-by-line
        for line in lines:
            sys.stdout.write("\x1b[2K\r" + line + "\n")

        sys.stdout.flush()
        return len(lines)
    def runTrain(self):
        prev = None
        for f in self.animation:
            prev = self.render_frame(f, prev)
            time.sleep(0.3)
